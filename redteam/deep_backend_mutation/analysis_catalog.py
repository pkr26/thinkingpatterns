from __future__ import annotations


def pytest(*selectors: str, timeout: int = 300) -> dict:
    return {
        "kind": "pytest",
        "cwd": "backend",
        "cmd": [
            ".venv/bin/python",
            "-m",
            "pytest",
            "-q",
            "-x",
            "--no-header",
            "-p",
            "no:cacheprovider",
            *selectors,
        ],
        "timeout": timeout,
    }


def m(identifier: str, name: str, file: str, find: str, replace: str, *tests: str) -> dict:
    return {
        "id": identifier,
        "name": name,
        "file": "backend/app/services/" + file + ".py",
        "find": find,
        "replace": replace,
        "tests": pytest(*tests),
    }


