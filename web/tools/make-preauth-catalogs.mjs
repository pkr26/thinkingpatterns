import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { runInNewContext } from 'node:vm';
import { transformSync } from 'esbuild';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const prefixes = ['login.', 'common.', 'app.', 'nav.', 'crisis.'];
const catalogs = {};
for (const locale of ['en', 'es']) {
 const source = await readFile(resolve(root, `src/locales/${locale}.ts`), 'utf8');
 const { code } = transformSync(source, { loader: 'ts', format: 'cjs' });
 const module = { exports: {} }; runInNewContext(code, { module, exports: module.exports });
 const full = module.exports[locale];
 catalogs[locale] = Object.fromEntries(Object.entries(full).filter(([key]) => prefixes.some(prefix => key.startsWith(prefix)) || key === 'settings.working'));
}
const result = '// Generated by tools/make-preauth-catalogs.mjs. Authenticated catalogs load after sign-in.\n' + Object.entries(catalogs).map(([locale,catalog]) => `export const ${locale}: Record<string,string> = ${JSON.stringify(catalog,null,2)};`).join('\n') + '\n';
await writeFile(resolve(root,'src/locales/preauth.ts'),result);
